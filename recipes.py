def suggest_recipes(available: list[str], top_n: int = 3) -> list[dict]:
    """
    Подбирает top_n рецептов, наиболее подходящих под список продуктов.

    Возвращает список словарей вида:
        {
            "name": ...,
            "match": ["продукт1", "продукт2"],
            "missing": ["продукт3"],
            "score": 0.66,
            "steps": [...],
        }
    """
    if not available:
        return []

    available_set = {x.strip().lower() for x in available if x.strip()}
    results = []

    for recipe in RECIPES:
        recipe_set = {x.lower() for x in recipe["ingredients"]}
        match = sorted(recipe_set & available_set)
        missing = sorted(recipe_set - available_set)

        if not match:
            continue

        score = len(match) / len(recipe_set)
        results.append(
            {
                "name": recipe["name"],
                "match": match,
                "missing": missing,
                "score": round(score, 2),
                "steps": recipe["steps"],
            }
        )

    # Сортировка: сначала больше совпадений, потом меньше недостающих
    results.sort(key=lambda r: (-r["score"], len(r["missing"])))
    return results[:top_n]